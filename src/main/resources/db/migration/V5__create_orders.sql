-- =====================================================================
-- V5: Đơn hàng và các dòng của đơn hàng
-- Tên bảng là "orders" vì ORDER là từ khóa SQL (ORDER BY).
-- =====================================================================

CREATE TABLE orders
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT         NOT NULL,
    status           VARCHAR(20)    NOT NULL,
    total_amount     NUMERIC(12, 2) NOT NULL,
    recipient_name   VARCHAR(100)   NOT NULL,
    phone            VARCHAR(20)    NOT NULL,
    shipping_address VARCHAR(500)   NOT NULL,
    paid_at          TIMESTAMPTZ,
    cancelled_at     TIMESTAMPTZ,
    -- Optimistic locking cho đơn hàng (GĐ 5b): chặn trường hợp user hủy đơn đúng
    -- lúc admin chuyển đơn sang SHIPPING.
    version          BIGINT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ    NOT NULL,
    updated_at       TIMESTAMPTZ    NOT NULL,

    -- Đơn hàng là dữ liệu kế toán: không xóa user nào đã có đơn (không CASCADE).
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'PAID', 'SHIPPING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_orders_total_amount CHECK (total_amount >= 0)
);

-- "Đơn hàng của tôi, mới nhất trước": lọc theo user_id rồi sắp theo created_at.
-- Index nhiều cột theo đúng thứ tự đó phục vụ trọn vẹn câu truy vấn (cả WHERE lẫn ORDER BY).
CREATE INDEX idx_orders_user_id_created_at ON orders (user_id, created_at DESC);

CREATE TABLE order_items
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    book_id    BIGINT         NOT NULL,
    -- SNAPSHOT: chép tên và giá TẠI THỜI ĐIỂM MUA. Sau này admin đổi giá hay đổi
    -- tên sách, đơn hàng cũ vẫn giữ đúng con số khách đã trả.
    book_title VARCHAR(255)   NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    quantity   INTEGER        NOT NULL,
    created_at TIMESTAMPTZ    NOT NULL,
    updated_at TIMESTAMPTZ    NOT NULL,

    CONSTRAINT uk_order_items_order_book UNIQUE (order_id, book_id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0)
);

-- Phục vụ GĐ 6 (đã mua sách này chưa?) và GĐ 7 (sách bán chạy): truy vấn theo book_id.
CREATE INDEX idx_order_items_book_id ON order_items (book_id);
