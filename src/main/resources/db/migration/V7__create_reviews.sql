CREATE TABLE reviews
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    book_id    BIGINT      NOT NULL,
    rating     INTEGER     NOT NULL,
    comment    TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,

    -- Mỗi người chỉ đánh giá một cuốn sách MỘT lần (muốn đổi ý thì sửa đánh giá cũ).
    CONSTRAINT uk_reviews_user_book UNIQUE (user_id, book_id),
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

-- Phục vụ 2 truy vấn theo sách:
--   - danh sách đánh giá của một cuốn, mới nhất trước (WHERE book_id = ? ORDER BY created_at DESC)
--   - điểm trung bình và số lượt đánh giá (WHERE book_id = ?)
CREATE INDEX idx_reviews_book_id_created_at ON reviews (book_id, created_at DESC);
