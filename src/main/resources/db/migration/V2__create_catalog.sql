-- =====================================================================

CREATE TABLE authors
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    bio        TEXT,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL
);

CREATE TABLE categories
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    -- slug: tên dạng URL, bỏ dấu, viết thường ("Văn học" -> "van-hoc").
    -- UNIQUE trên slug chặn luôn các tên chỉ khác nhau ở hoa/thường hoặc dấu.
    slug       VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uk_categories_name UNIQUE (name),
    CONSTRAINT uk_categories_slug UNIQUE (slug)
);

CREATE TABLE books
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(255)   NOT NULL,
    isbn           VARCHAR(20)    NOT NULL,
    description    TEXT,
    -- NUMERIC lưu số thập phân CHÍNH XÁC; không dùng REAL/DOUBLE cho tiền.
    price          NUMERIC(12, 2) NOT NULL,
    stock_quantity INTEGER        NOT NULL DEFAULT 0,
    category_id    BIGINT         NOT NULL,
    published_year INTEGER,
    -- Soft delete: "xóa" sách chỉ đặt active = false, dòng dữ liệu vẫn còn
    -- để các đơn hàng cũ (GĐ 5) vẫn tham chiếu được.
    active         BOOLEAN        NOT NULL DEFAULT TRUE,
    -- Dùng cho optimistic locking (@Version): mỗi lần UPDATE tăng thêm 1.
    version        BIGINT         NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ    NOT NULL,
    updated_at     TIMESTAMPTZ    NOT NULL,

    CONSTRAINT uk_books_isbn UNIQUE (isbn),
    CONSTRAINT fk_books_category FOREIGN KEY (category_id) REFERENCES categories (id),
    -- CHECK là lớp bảo vệ cuối cùng: kể cả khi code có bug, DB cũng không
    -- bao giờ chứa giá âm hay tồn kho âm.
    CONSTRAINT ck_books_price CHECK (price >= 0),
    CONSTRAINT ck_books_stock_quantity CHECK (stock_quantity >= 0)
);

-- Bảng nối cho quan hệ nhiều-nhiều: một sách có nhiều tác giả, một tác giả viết nhiều sách.
CREATE TABLE book_authors
(
    book_id   BIGINT NOT NULL,
    author_id BIGINT NOT NULL,

    CONSTRAINT pk_book_authors PRIMARY KEY (book_id, author_id),
    CONSTRAINT fk_book_authors_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE,
    CONSTRAINT fk_book_authors_author FOREIGN KEY (author_id) REFERENCES authors (id)
);

-- PK (book_id, author_id) đã phục vụ tìm theo book_id (cột đứng đầu).
-- Tìm theo author_id (lọc sách theo tác giả, kiểm tra tác giả còn sách không) cần index riêng.
CREATE INDEX idx_book_authors_author_id ON book_authors (author_id);
CREATE INDEX idx_books_category_id ON books (category_id);
CREATE INDEX idx_books_price ON books (price);
