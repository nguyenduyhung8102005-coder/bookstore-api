-- =====================================================================
-- V4: Giỏ hàng. Mỗi user có đúng một giỏ, nên không cần bảng "carts" riêng:
-- giỏ của user = tất cả các dòng cart_items có user_id của user đó.
-- =====================================================================

CREATE TABLE cart_items
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    book_id    BIGINT      NOT NULL,
    quantity   INTEGER     NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,

    -- Mỗi cuốn sách chỉ xuất hiện MỘT dòng trong giỏ của một user (thêm lần
    -- nữa thì cộng dồn số lượng). Ràng buộc này cũng chặn trường hợp người
    -- dùng bấm "Thêm vào giỏ" 2 lần liên tiếp tạo ra 2 dòng trùng.
    -- PostgreSQL tạo sẵn index cho UNIQUE; vì user_id đứng đầu, index này
    -- phục vụ luôn câu "lấy giỏ của user" (WHERE user_id = ?).
    CONSTRAINT uk_cart_items_user_book UNIQUE (user_id, book_id),
    CONSTRAINT fk_cart_items_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0)
);
